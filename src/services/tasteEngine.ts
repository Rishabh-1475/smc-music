/**
 * RYTHEMX Taste-Learning Engine & Smart Auto-Playlist Generator
 * Learns listening habits, artist affinities, language preferences,
 * and continuously auto-generates personalized dynamic mixes.
 * Package: co.singhsmusic.rhythmx
 */

import { Song } from '../types/music';
import { extractCanonicalTitle, filterRelatedCandidates } from './trackDedupe';
import { fetchSongSuggestions, fetchSongsByQuery } from './api';

export interface LikedTrackItem {
  song: Song;
  likedAt: number;
}

export interface TasteProfile {
  artistAffinities: Record<string, number>;
  languageAffinities: Record<string, number>;
  genreAffinities: Record<string, number>;
  playCounts: Record<string, number>;
  lastPlayedTimes: Record<string, number>;
  sessionSkippedArtists: Record<string, number>;
  likedTracks: LikedTrackItem[];
}

export interface AutoPlaylist {
  id: string;
  name: string;
  subtitle: string;
  description: string;
  coverArt: string;
  isAutoGenerated: true;
  tracks: Song[];
  updatedAt: number;
  category: 'liked-mix' | 'vibe-mix' | 'artist-spotlight';
}

const TASTE_KEY = 'rythemx_taste_profile_v1';
const PLAYLISTS_KEY = 'rythemx_auto_playlists_v1';

class TasteEngine {
  private profile: TasteProfile;
  private autoPlaylists: AutoPlaylist[] = [];
  private rebuildPromise: Promise<AutoPlaylist[]> | null = null;
  private listeners: Set<(playlists: AutoPlaylist[]) => void> = new Set();

  constructor() {
    this.profile = this.loadProfile();
    this.autoPlaylists = this.loadPlaylists();
  }

  private loadProfile(): TasteProfile {
    if (typeof window === 'undefined') {
      return {
        artistAffinities: {},
        languageAffinities: {},
        genreAffinities: {},
        playCounts: {},
        lastPlayedTimes: {},
        sessionSkippedArtists: {},
        likedTracks: []
      };
    }
    try {
      const raw = localStorage.getItem(TASTE_KEY);
      if (raw) return JSON.parse(raw);
    } catch {}

    // Backwards-compatible import from rythemx_liked_songs
    const legacyLikedRaw = localStorage.getItem('rythemx_liked_songs');
    const legacyLiked: Song[] = legacyLikedRaw ? JSON.parse(legacyLikedRaw) : [];

    return {
      artistAffinities: {},
      languageAffinities: {},
      genreAffinities: {},
      playCounts: {},
      lastPlayedTimes: {},
      sessionSkippedArtists: {},
      likedTracks: legacyLiked.map((s) => ({ song: s, likedAt: Date.now() }))
    };
  }

  private loadPlaylists(): AutoPlaylist[] {
    if (typeof window === 'undefined') return [];
    try {
      const raw = localStorage.getItem(PLAYLISTS_KEY);
      if (raw) return JSON.parse(raw);
    } catch {}
    return [];
  }

  private save() {
    if (typeof window === 'undefined') return;
    try {
      localStorage.setItem(TASTE_KEY, JSON.stringify(this.profile));
      localStorage.setItem(PLAYLISTS_KEY, JSON.stringify(this.autoPlaylists));
    } catch (e) {
      console.warn('[TasteEngine] Storage error:', e);
    }
  }

  public getProfile(): TasteProfile {
    return this.profile;
  }

  public getAutoPlaylists(): AutoPlaylist[] {
    return this.autoPlaylists;
  }

  public subscribe(cb: (playlists: AutoPlaylist[]) => void): () => void {
    this.listeners.add(cb);
    return () => this.listeners.delete(cb);
  }

  private notify() {
    this.listeners.forEach((cb) => cb(this.autoPlaylists));
  }

  /**
   * Normalize and extract primary artists
   */
  private getArtists(song: Song): string[] {
    const raw = song.primaryArtists || (song as any).artist || '';
    return raw
      .split(',')
      .map((a: string) => a.replace(/feat\..*$/i, '').trim())
      .filter(Boolean);
  }

  /**
   * User Likes a Track
   */
  public like(song: Song) {
    const exists = this.profile.likedTracks.some((item) => item.song.id === song.id);
    if (!exists) {
      this.profile.likedTracks.unshift({ song, likedAt: Date.now() });
    }

    // Boost artist affinity (+6)
    const artists = this.getArtists(song);
    artists.forEach((art) => {
      this.profile.artistAffinities[art] = (this.profile.artistAffinities[art] || 0) + 6;
    });

    // Boost language affinity (+4)
    const lang = (song.language || 'hindi').toLowerCase();
    this.profile.languageAffinities[lang] = (this.profile.languageAffinities[lang] || 0) + 4;

    this.save();
    this.rebuildAutoPlaylists();
  }

  /**
   * User Unlikes a Track
   */
  public unlike(songId: string) {
    this.profile.likedTracks = this.profile.likedTracks.filter(
      (item) => item.song.id !== songId
    );
    this.save();
    this.rebuildAutoPlaylists();
  }

  /**
   * Track Played to Completion (>= 65% of duration or > 90s)
   */
  public complete(song: Song) {
    if (!song || !song.id) return;
    this.profile.playCounts[song.id] = (this.profile.playCounts[song.id] || 0) + 1;
    this.profile.lastPlayedTimes[song.id] = Date.now();

    const artists = this.getArtists(song);
    artists.forEach((art) => {
      this.profile.artistAffinities[art] = (this.profile.artistAffinities[art] || 0) + 2;
    });

    const lang = (song.language || 'hindi').toLowerCase();
    this.profile.languageAffinities[lang] = (this.profile.languageAffinities[lang] || 0) + 1;

    this.save();
  }

  /**
   * Quick Skip (< 20s listened): Temporarily penalize artist in session
   */
  public skipEarly(song: Song) {
    if (!song) return;
    const artists = this.getArtists(song);
    artists.forEach((art) => {
      this.profile.sessionSkippedArtists[art] =
        (this.profile.sessionSkippedArtists[art] || 0) + 2;
    });
  }

  /**
   * Get top N artists by affinity
   */
  public getTopArtists(n = 3): { artist: string; score: number }[] {
    return Object.entries(this.profile.artistAffinities)
      .map(([artist, score]) => ({
        artist,
        score: score - (this.profile.sessionSkippedArtists[artist] || 0)
      }))
      .sort((a, b) => b.score - a.score)
      .slice(0, n);
  }

  /**
   * Get top N languages by affinity
   */
  public getTopLanguages(n = 2): string[] {
    return Object.entries(this.profile.languageAffinities)
      .sort((a, b) => b[1] - a[1])
      .map((entry) => entry[0])
      .slice(0, n);
  }

  /**
   * Rebuild Smart Auto-Playlists from user likes and listening history
   */
  public rebuildAutoPlaylists(): Promise<AutoPlaylist[]> {
    if (this.rebuildPromise) {
      return this.rebuildPromise;
    }
    this.rebuildPromise = this.executeRebuild().finally(() => {
      this.rebuildPromise = null;
    });
    return this.rebuildPromise;
  }

  private async executeRebuild(): Promise<AutoPlaylist[]> {

    try {
      const likedSongs = this.profile.likedTracks.map((item) => item.song);
      const newPlaylists: AutoPlaylist[] = [];

      // 1. "Your Liked Mix" / "On Repeat"
      if (likedSongs.length > 0) {
        // Blend top liked tracks with related discoveries
        const seedSongs = likedSongs.slice(0, 5);
        let relatedDiscoveries: Song[] = [];

        try {
          const suggestions = await Promise.allSettled(
            seedSongs.slice(0, 2).map((s) => fetchSongSuggestions(s.id, 10, s))
          );
          const rawRelated: Song[] = [];
          for (const res of suggestions) {
            if (res.status === 'fulfilled' && Array.isArray(res.value)) {
              rawRelated.push(...res.value);
            }
          }
          relatedDiscoveries = filterRelatedCandidates(rawRelated, likedSongs);
        } catch {}

        // Combine liked + discoveries (60% liked, 40% discoveries)
        const blended = [...likedSongs.slice(0, 12), ...relatedDiscoveries.slice(0, 8)];

        newPlaylists.push({
          id: 'auto_liked_mix',
          name: 'Your Liked Mix',
          subtitle: `Auto-updated from your likes • ${blended.length} tracks`,
          description: 'Your favorite saved songs seamlessly blended with fresh related discoveries.',
          coverArt: likedSongs[0]?.imageUrl || 'https://images.unsplash.com/photo-1518709268805-4e9042af9f23?w=500&q=80',
          isAutoGenerated: true,
          tracks: blended,
          updatedAt: Date.now(),
          category: 'liked-mix'
        });
      }

      // 2. Language / Vibe Auto-Mixes
      // Check for Punjabi / Haryanvi
      const punjabiHaryanviLiked = likedSongs.filter((s) => {
        const l = (s.language || '').toLowerCase();
        const t = (s.name || s.title || '').toLowerCase();
        const a = (s.primaryArtists || '').toLowerCase();
        return (
          l === 'punjabi' ||
          l === 'haryanvi' ||
          a.includes('saini') ||
          a.includes('moose wala') ||
          a.includes('karan aujla') ||
          a.includes('shubh') ||
          t.includes('gaadi')
        );
      });

      if (punjabiHaryanviLiked.length > 0) {
        let recs: Song[] = [];
        try {
          const fetched = await fetchSongsByQuery('Top Punjabi Haryanvi Hits 2026');
          recs = filterRelatedCandidates(fetched, likedSongs);
        } catch {}

        const tracks = [...punjabiHaryanviLiked, ...recs.slice(0, 10)];
        newPlaylists.push({
          id: 'auto_punjabi_desi',
          name: 'Punjabi & Desi Fire Mix',
          subtitle: `Auto-curated for you • ${tracks.length} tracks`,
          description: 'High-energy Desi, Punjabi and Haryanvi bangers matched to your favorites.',
          coverArt: punjabiHaryanviLiked[0]?.imageUrl || 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=500&q=80',
          isAutoGenerated: true,
          tracks,
          updatedAt: Date.now(),
          category: 'vibe-mix'
        });
      }

      // Check for Hindi / Bollywood
      const hindiLiked = likedSongs.filter((s) => {
        const l = (s.language || '').toLowerCase();
        return l === 'hindi' || !l;
      });

      if (hindiLiked.length >= 1) {
        let recs: Song[] = [];
        try {
          const fetched = await fetchSongsByQuery('Trending Bollywood Romantic Hits 2026');
          recs = filterRelatedCandidates(fetched, likedSongs);
        } catch {}

        const tracks = [...hindiLiked.slice(0, 10), ...recs.slice(0, 10)];
        newPlaylists.push({
          id: 'auto_bollywood_soul',
          name: 'Bollywood & Soul Mix',
          subtitle: `Auto-curated from your Hindi likes • ${tracks.length} tracks`,
          description: 'Melodic Bollywood, Sufi and acoustic tracks tailored to your romantic tastes.',
          coverArt: hindiLiked[0]?.imageUrl || 'https://images.unsplash.com/photo-1518709268805-4e9042af9f23?w=500&q=80',
          isAutoGenerated: true,
          tracks,
          updatedAt: Date.now(),
          category: 'vibe-mix'
        });
      }

      // Check for Bhojpuri
      const bhojpuriLiked = likedSongs.filter((s) => {
        const l = (s.language || '').toLowerCase();
        const a = (s.primaryArtists || '').toLowerCase();
        return l === 'bhojpuri' || a.includes('pawan') || a.includes('khesari') || a.includes('shilpi');
      });

      if (bhojpuriLiked.length > 0) {
        let recs: Song[] = [];
        try {
          const fetched = await fetchSongsByQuery('Bhojpuri Top Dhamaka 2026');
          recs = filterRelatedCandidates(fetched, likedSongs);
        } catch {}

        const tracks = [...bhojpuriLiked, ...recs.slice(0, 10)];
        newPlaylists.push({
          id: 'auto_bhojpuri_superhits',
          name: 'Bhojpuri Superhits Mix',
          subtitle: `Auto-curated for you • ${tracks.length} tracks`,
          description: 'Trending Bhojpuri chartbusters matching your saved favorites.',
          coverArt: bhojpuriLiked[0]?.imageUrl || 'https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=500&q=80',
          isAutoGenerated: true,
          tracks,
          updatedAt: Date.now(),
          category: 'vibe-mix'
        });
      }

      // 3. Artist Spotlight Mixes (Top 2 artists)
      const topArtists = this.getTopArtists(2);
      for (const { artist } of topArtists) {
        if (!artist || artist === 'Various Artists') continue;
        const artistLiked = likedSongs.filter((s) =>
          (s.primaryArtists || '').toLowerCase().includes(artist.toLowerCase())
        );

        let artistTracks: Song[] = [];
        try {
          const fetched = await fetchSongsByQuery(`${artist} Hits`);
          artistTracks = filterRelatedCandidates(fetched, likedSongs);
        } catch {}

        const tracks = [...artistLiked, ...artistTracks.slice(0, 12)];
        if (tracks.length >= 4) {
          newPlaylists.push({
            id: `auto_artist_${artist.toLowerCase().replace(/[^a-z0-9]/g, '_')}`,
            name: `${artist} & Friends`,
            subtitle: `Artist Spotlight • ${tracks.length} tracks`,
            description: `A personalized session highlighting ${artist} alongside handpicked collaborator tracks.`,
            coverArt: tracks[0]?.imageUrl || 'https://images.unsplash.com/photo-1518709268805-4e9042af9f23?w=500&q=80',
            isAutoGenerated: true,
            tracks,
            updatedAt: Date.now(),
            category: 'artist-spotlight'
          });
        }
      }

      if (newPlaylists.length > 0) {
        this.autoPlaylists = newPlaylists;
        this.save();
        this.notify();
      }
    } catch (err) {
      console.warn('[TasteEngine] Error rebuilding auto-playlists:', err);
    }

    return this.autoPlaylists;
  }

  /**
   * Personalized Home Recommendation Shelves
   */
  public async getPersonalizedShelves(): Promise<{
    becauseYouLiked: { title: string; subtitle: string; tracks: Song[] } | null;
    autoMixes: AutoPlaylist[];
    replayFavorites: Song[];
  }> {
    const likedSongs = this.profile.likedTracks.map((item) => item.song);

    // 1. Replay Favorites (liked + highest play count, prioritized by not recently played)
    const now = Date.now();
    const replayFavorites = [...likedSongs]
      .sort((a, b) => {
        const lastA = this.profile.lastPlayedTimes[a.id] || 0;
        const lastB = this.profile.lastPlayedTimes[b.id] || 0;
        // Prioritize songs not heard in the last 2 hours
        const scoreA = (this.profile.playCounts[a.id] || 1) * 10 - (now - lastA < 7200000 ? 50 : 0);
        const scoreB = (this.profile.playCounts[b.id] || 1) * 10 - (now - lastB < 7200000 ? 50 : 0);
        return scoreB - scoreA;
      })
      .slice(0, 10);

    // 2. Because You Liked "[Latest Liked Song]"
    let becauseYouLiked: { title: string; subtitle: string; tracks: Song[] } | null = null;
    const latestLiked = likedSongs[0];

    if (latestLiked) {
      try {
        const raw = await fetchSongSuggestions(latestLiked.id, 15, latestLiked);
        const filtered = filterRelatedCandidates(raw, [latestLiked]);
        if (filtered.length >= 4) {
          becauseYouLiked = {
            title: `Because You Liked "${latestLiked.name || latestLiked.title}"`,
            subtitle: 'RECOMMENDED FOR YOU',
            tracks: filtered.slice(0, 10)
          };
        }
      } catch {}
    }

    return {
      becauseYouLiked,
      autoMixes: this.autoPlaylists,
      replayFavorites
    };
  }
}

export const tasteEngine = new TasteEngine();
